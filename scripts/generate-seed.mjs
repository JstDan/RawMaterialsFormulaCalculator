// Generates the raw-material seed from Data/Raw_Materials_Price_List.xlsx:
//   - supabase/migrations/20261013000002_seed_raw_materials.sql (Supabase)
//   - src/data/seedMaterials.json (local demo mode)
// Usage: node scripts/generate-seed.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import * as XLSX from 'xlsx';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');

const REGULATORY_NOTES = {
  'NMN (B-NicotinamideMononucleotide)':
    'Novel Food – not authorised in the EU Union list. Do not use in food supplements for the EU market.',
  'Fisetin 98%': 'Novel Food status – no EU authorisation known. Verify before use.',
  'Shilajit Extract (20% fulvic acid)': 'Novel Food status unclear in the EU – verify before use.',
  'Nicotinamide Riboside (NR)':
    'Authorised Novel Food only as NR chloride, with max daily levels – check form & spec.',
  'Spermidine 1%': 'Authorised Novel Food only as spermidine-rich wheat germ extract – verify source & spec.',
  Citicoline: 'Authorised Novel Food – conditions of use and max levels apply.',
  'Vitamin K2': 'Check form (menaquinone MK-7 as authorised Novel Food) and spec.',
  'Methylfolate L-5-MTHF': 'Check salt form – only authorised folate forms permitted.',
  Phosphatidylserine: 'Check source – soy PS is fine; fish-derived PS is a specific authorised Novel Food.',
  'D-Chiro-Inositol': 'Verify Novel Food status before use.',
  'Tributyrin (Glyceryl Tributyrate) Powder 60%': 'Verify Novel Food status before use.',
  'Green Tea Extract (50% EGCG)':
    'Reg. (EU) 2022/2340: EGCG must stay below 800 mg/day; mandatory label warnings.',
  Melatonin: 'National (BG) limits/classification apply – verify dose.',
  'Berberine HCI': 'Regulatory status under review in the EU – verify before use.',
};

const wb = XLSX.read(readFileSync(join(root, 'Data', 'Raw_Materials_Price_List.xlsx')));
const rows = XLSX.utils.sheet_to_json(wb.Sheets[wb.SheetNames[0]], { defval: null });

const materials = rows.map((r) => {
  const name = String(r['Raw Material']).trim();
  const price = Number(r['Price DDP/EUR/kg']);
  if (!name || !Number.isFinite(price)) throw new Error(`Invalid row: ${JSON.stringify(r)}`);
  return { name, price_eur_per_kg: price, regulatory_note: REGULATORY_NOTES[name] ?? null };
});

const names = new Set(materials.map((m) => m.name));
if (names.size !== materials.length) throw new Error('Duplicate material names in the price list');
for (const n of Object.keys(REGULATORY_NOTES)) {
  if (!names.has(n)) throw new Error(`Regulatory note for unknown material: ${n}`);
}

const q = (s) => (s === null ? 'null' : `'${s.replace(/'/g, "''")}'`);
const sql = [
  '-- Seed: raw materials from Data/Raw_Materials_Price_List.xlsx (generated by scripts/generate-seed.mjs).',
  'insert into public.raw_materials (name, price_eur_per_kg, regulatory_note) values',
  materials.map((m) => `  (${q(m.name)}, ${m.price_eur_per_kg}, ${q(m.regulatory_note)})`).join(',\n'),
  'on conflict (name) do update set',
  '  price_eur_per_kg = excluded.price_eur_per_kg,',
  '  regulatory_note = excluded.regulatory_note;',
  '',
].join('\n');

writeFileSync(join(root, 'supabase', 'migrations', '20261013000002_seed_raw_materials.sql'), sql);
writeFileSync(join(root, 'src', 'data', 'seedMaterials.json'), JSON.stringify(materials, null, 2) + '\n');
console.log(`Seeded ${materials.length} raw materials (${Object.keys(REGULATORY_NOTES).length} with regulatory notes).`);
